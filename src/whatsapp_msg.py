import os
from dotenv import load_dotenv
from pywhatkit.whats import sendwhatmsg_instantly

load_dotenv()


def format_indian_currency(amount) -> str:
    try:
        val = int(round(float(amount)))
    except (ValueError, TypeError):
        return f"₹{amount}"

    s = str(abs(val))
    if len(s) <= 3:
        formatted = s
    else:
        last3 = s[-3:]
        remaining = s[:-3]
        parts = []
        while len(remaining) > 2:
            parts.insert(0, remaining[-2:])
            remaining = remaining[:-2]
        if remaining:
            parts.insert(0, remaining)
        formatted = ",".join(parts) + "," + last3

    prefix = "-₹" if val < 0 else "₹"
    return f"{prefix}{formatted}"


def send_lead_via_whatsapp(lead_details: dict, result: str):
    try:
        mobile_number = os.getenv("mobile_number")
        if not mobile_number:
            load_dotenv()
            mobile_number = os.getenv("mobile_number")

        if not mobile_number:
            print("Mobile number not found in .env")
            return
        mobile_number = mobile_number.strip(" \"'")

        formatted_budget = format_indian_currency(lead_details.get("Budget", 0))

        message = f"""🚀 SALES AI AUTOMATION
━━━━━━━━━━━━━━━━━━

🔔 NEW LEAD ALERT

📋 LEAD DETAILS

Industry          : {lead_details['Industry']}
Company Size      : {lead_details['Company Size']}
Website Visits    : {lead_details['Website Visits']}
Emails Opened     : {lead_details['Emails Opened']}
Demo Requested    : {lead_details['Demo']}
Budget            : {formatted_budget}

━━━━━━━━━━━━━━━━━━
🎯 ML PREDICTION: {result}

Generated by Sales AI Automation"""

        sendwhatmsg_instantly(
            mobile_number,
            message,
            wait_time=20,
            tab_close=True,
            close_time=5,
            browser=None
        )

        print("WhatsApp message sent successfully!")
        return "WhatsApp message sent successfully!"

    except Exception as e:
        print("WhatsApp Error:", e)
        return f"WhatsApp Error: {str(e)}"
